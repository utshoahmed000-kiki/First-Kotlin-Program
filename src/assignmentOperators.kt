fun main (){

    var number = 15
    // Simple assignment
    println("value after = $number")
    // Add and assign
    number += 6
    println("value after = $number")
    // Subtract and assign
    number -=4
    println("value after = $number")
    // Multiply and assign
    number *=9
    println("value after = $number")
    // Divide and assign
    number /=3
    println("value after = $number")
    // Modulus and assign
    number %= 7
    println("value after = $number")

}