fun main (){
    val z=25
    val x=15
    //addition
    val sum =z+x
    println("addition : $z + $sum = $sum")
    // Subtraction
    val minus = z-x
    println ("Subtraction : $z - $sum = $minus")
    //Multiplication
    val multiplication = z*x
    println ("Multiplication : $z * $x = $multiplication")
    //Division
    val division = z/x
    println("Division: $z / $x = $division")
    // Modulus (%)
    val modulus = z % x
    println("Modulus: $z % $x = $modulus")

}