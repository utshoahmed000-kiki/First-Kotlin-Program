fun main (){

    val m = 30
    val n = 40

    // Equal to
    println("m == n : ${m == n}")
    // Not equal to
    println("m != n : ${m != n}")
    // Greater than
    println("m > n  : ${m > n}")
    // Less than
    println("m < n  : ${m < n}")
    // Greater than or equal to
    println("m >= n : ${m >= n}")
    // Less than or equal to
    println("m <= n : ${m <= n}")

}